/**
 * Toolbar tool plugins. Each plugin describes a parameter form; `generate`
 * returns the OpenSCAD code inserted into the editor and `preview` returns a
 * self-contained snippet compiled for the dialog's live 3D preview.
 *
 * To add a plugin: write a ToolPlugin object and append it to PLUGINS.
 */

export type ParamValue = number | boolean | string;

export interface PluginParam {
  key: string;
  label: string;
  type: "number" | "int" | "bool" | "select";
  default: ParamValue;
  min?: number;
  max?: number;
  step?: number;
  options?: string[];
  help?: string;
}

export interface ToolPlugin {
  id: string;
  name: string;
  blurb: string;
  params: PluginParam[];
  generate(v: Record<string, ParamValue>): string;
  preview(v: Record<string, ParamValue>): string;
}

const n = (v: ParamValue) => Number(v);
const b = (v: ParamValue) => (v ? "true" : "false");

// ---------------------------------------------------------------- gear

const gearBuilder: ToolPlugin = {
  id: "gear",
  name: "Gear builder",
  blurb: "Involute spur gear with optional hub, bore, helix and lightening holes.",
  params: [
    { key: "m", label: "Module (mm/tooth)", type: "number", default: 2, min: 0.5, max: 6, step: 0.25 },
    { key: "z", label: "Teeth", type: "int", default: 20, min: 6, max: 80, step: 1 },
    { key: "pa", label: "Pressure angle", type: "number", default: 20, min: 14, max: 30, step: 0.5 },
    { key: "thickness", label: "Thickness", type: "number", default: 6, min: 1, max: 30, step: 0.5 },
    { key: "bore", label: "Bore Ø", type: "number", default: 6, min: 0, max: 30, step: 0.5 },
    { key: "hub_d", label: "Hub Ø (0 = none)", type: "number", default: 14, min: 0, max: 60, step: 1 },
    { key: "hub_h", label: "Hub extra height", type: "number", default: 4, min: 0, max: 30, step: 0.5 },
    { key: "helix", label: "Helix twist (°)", type: "number", default: 0, min: -45, max: 45, step: 1 },
    { key: "spoke_holes", label: "Lightening holes", type: "int", default: 4, min: 0, max: 12, step: 1 },
  ],
  generate(v) {
    return `// Involute spur gear (generated by the WebSCAD gear builder)
module spur_gear(m = ${n(v.m)}, z = ${n(v.z)}, pa = ${n(v.pa)}, thickness = ${n(v.thickness)},
                 bore = ${n(v.bore)}, hub_d = ${n(v.hub_d)}, hub_h = ${n(v.hub_h)},
                 helix = ${n(v.helix)}, spoke_holes = ${n(v.spoke_holes)}) {
    rp = m * z / 2;           // pitch radius
    rb = rp * cos(pa);        // base circle
    ra = rp + m;              // tip radius
    rr = rp - 1.25 * m;       // root radius
    K = 8;                    // samples per flank

    function ix(t) = rb * (cos(t) + PI / 180 * t * sin(t));
    function iy(t) = rb * (sin(t) - PI / 180 * t * cos(t));
    function irad(t) = sqrt(ix(t) ^ 2 + iy(t) ^ 2);
    function itheta(t) = atan2(iy(t), ix(t));
    function ppt(r, a) = [r * cos(a), r * sin(a)];

    ta = sqrt((ra / rb) ^ 2 - 1) * 180 / PI;
    tp = sqrt((rp / rb) ^ 2 - 1) * 180 / PI;
    thp = itheta(tp);

    function aL(t) = itheta(t) - thp - 90 / z;
    function aR(t) = -(itheta(t) - thp) + 90 / z;

    outline = [for (k = [0 : z - 1]) each concat(
        [ppt(rr, k * 360 / z - 180 / z)],
        [ppt(rr, k * 360 / z + aL(0))],
        [for (i = [0 : K]) ppt(irad(ta * i / K), k * 360 / z + aL(ta * i / K))],
        [for (i = [K : -1 : 0]) ppt(irad(ta * i / K), k * 360 / z + aR(ta * i / K))],
        [ppt(rr, k * 360 / z + aR(0))]
    )];

    ring_r = (rr + max(bore, hub_d) / 2) / 2;          // spoke-hole circle
    hole_r = (rr - max(bore, hub_d) / 2) * 0.22;

    difference() {
        union() {
            linear_extrude(thickness, twist = helix,
                           slices = helix == 0 ? 1 : 16)
                polygon(outline);
            if (hub_d > 0)
                cylinder(h = thickness + hub_h, d = hub_d, $fn = 48);
        }
        if (bore > 0)
            translate([0, 0, -1])
                cylinder(h = thickness + hub_h + 2, d = bore, $fn = 32);
        if (spoke_holes > 0 && hole_r > 0.8)
            for (i = [0 : spoke_holes - 1])
                rotate([0, 0, (i + 0.5) * 360 / spoke_holes])
                    translate([ring_r, 0, -1])
                        cylinder(h = thickness + 2, r = hole_r, $fn = 24);
    }
}

spur_gear();
`;
  },
  preview(v) {
    return this.generate(v);
  },
};

// ------------------------------------------------------------ polar array

const polarArray: ToolPlugin = {
  id: "polar-array",
  name: "Polar array",
  blurb: "Distribute children in a circle (or helix) around the Z axis.",
  params: [
    { key: "count", label: "Count", type: "int", default: 8, min: 2, max: 64, step: 1 },
    { key: "radius", label: "Radius", type: "number", default: 22, min: 0, max: 200, step: 1 },
    { key: "start", label: "Start angle", type: "number", default: 0, min: -360, max: 360, step: 5 },
    { key: "sweep", label: "Sweep (°)", type: "number", default: 360, min: 10, max: 360, step: 5 },
    { key: "pitch", label: "Z pitch per item (helix)", type: "number", default: 0, min: -20, max: 20, step: 0.5 },
    { key: "rotate_items", label: "Rotate items with circle", type: "bool", default: true },
  ],
  generate(v) {
    return `// Polar array (generated by WebSCAD tools) — wraps its children
module polar_array(count = ${n(v.count)}, radius = ${n(v.radius)}, start = ${n(v.start)},
                   sweep = ${n(v.sweep)}, pitch = ${n(v.pitch)}, rotate_items = ${b(v.rotate_items)}) {
    astep = sweep >= 360 ? sweep / count : sweep / max(1, count - 1);
    for (i = [0 : count - 1]) {
        ang = start + i * astep;
        rotate([0, 0, ang])
            translate([radius, 0, i * pitch])
                rotate([0, 0, rotate_items ? 0 : -ang])
                    children();
    }
}

polar_array()
    cylinder(h = 8, r = 3);   // <- replace with your shape
`;
  },
  preview(v) {
    return this.generate(v).replace(
      "cylinder(h = 8, r = 3);   // <- replace with your shape",
      "cube([6, 3, 8]);",
    );
  },
};

