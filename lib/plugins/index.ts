const gridArray: ToolPlugin = {
  id: "grid-array",
  name: "Grid array",
  blurb: "Distribute children on a rectangular (or 3D) grid.",
  params: [
    { key: "nx", label: "Count X", type: "int", default: 4, min: 1, max: 30, step: 1 },
    { key: "ny", label: "Count Y", type: "int", default: 3, min: 1, max: 30, step: 1 },
    { key: "nz", label: "Count Z", type: "int", default: 1, min: 1, max: 30, step: 1 },
    { key: "dx", label: "Spacing X", type: "number", default: 15, min: 1, max: 100, step: 1 },
    { key: "dy", label: "Spacing Y", type: "number", default: 15, min: 1, max: 100, step: 1 },
    { key: "dz", label: "Spacing Z", type: "number", default: 15, min: 1, max: 100, step: 1 },
    { key: "center", label: "Center on origin", type: "bool", default: true },
  ],
  generate(v) {
    return `// Grid array (generated by WebSCAD tools) — wraps its children
module grid_array(nx = ${n(v.nx)}, ny = ${n(v.ny)}, nz = ${n(v.nz)},
                  dx = ${n(v.dx)}, dy = ${n(v.dy)}, dz = ${n(v.dz)}, center = ${b(v.center)}) {
    offs = center ? [-(nx - 1) * dx / 2, -(ny - 1) * dy / 2, -(nz - 1) * dz / 2]
                  : [0, 0, 0];
    for (i = [0 : nx - 1], j = [0 : ny - 1], k = [0 : nz - 1])
        translate(offs + [i * dx, j * dy, k * dz])
            children();
}

grid_array()
    cylinder(h = 6, r = 4);   // <- replace with your shape
`;
  },
  preview(v) {
    return this.generate(v);
  },
};

// -------------------------------------------------------- surface scatter

const surfaceScatter: ToolPlugin = {
  id: "scatter",
  name: "Surface scatter",
  blurb: "Distribute children over the surface of a sphere, oriented along the surface normal (Fibonacci spiral).",
  params: [
    { key: "count", label: "Count", type: "int", default: 48, min: 3, max: 300, step: 1 },
    { key: "radius", label: "Sphere radius", type: "number", default: 24, min: 2, max: 150, step: 1 },
    { key: "hemisphere", label: "Upper hemisphere only", type: "bool", default: false },
    { key: "align_normal", label: "Orient +Z along normal", type: "bool", default: true },
    { key: "show_host", label: "Show host sphere (%)", type: "bool", default: true },
  ],
  generate(v) {
    return `// Surface scatter (generated by WebSCAD tools) — distributes children
// on a sphere using a Fibonacci spiral; each child's +Z points outward.
module sphere_scatter(count = ${n(v.count)}, radius = ${n(v.radius)},
                      hemisphere = ${b(v.hemisphere)}, align_normal = ${b(v.align_normal)}) {
    ga = 137.50776;                       // golden angle
    for (i = [0 : count - 1]) {
        zu = 1 - (i + 0.5) * (hemisphere ? 1 : 2) / count;   // unit z
        ru = sqrt(1 - zu * zu);
        az = i * ga;
        polar = acos(zu);
        translate(radius * [ru * cos(az), ru * sin(az), zu])
            rotate(align_normal ? [0, polar, az] : [0, 0, 0])
                children();
    }
}

${v.show_host ? `%sphere(${n(v.radius)}, $fn = 48);   // host object (background modifier)\n` : ""}sphere_scatter()
    cylinder(h = 5, r1 = 1.8, r2 = 0, $fn = 16);   // <- replace with your shape
`;
  },
  preview(v) {
    return this.generate(v);
  },
};

// ------------------------------------------------------------ mirror copy

const mirrorCopy: ToolPlugin = {
  id: "mirror-copy",
  name: "Mirror copy",
  blurb: "Keep the original and add a mirrored twin — handy for symmetric parts.",
  params: [
    { key: "axis", label: "Mirror across", type: "select", default: "X", options: ["X", "Y", "Z"] },
  ],
  generate(v) {
    const vec = v.axis === "X" ? "[1, 0, 0]" : v.axis === "Y" ? "[0, 1, 0]" : "[0, 0, 1]";
    return `// Mirror copy (generated by WebSCAD tools) — wraps its children
module mirror_copy(v = ${vec}) {
    children();
    mirror(v) children();
}

mirror_copy()
    translate([12, 4, 0]) cube([8, 5, 10]);   // <- replace with your shape
`;
  },
  preview(v) {
    return this.generate(v);
  },
};

// ----------------------------------------------------------------- align

const alignTool: ToolPlugin = {
  id: "align",
  name: "Align to origin",
  blurb: "Position the bounding box of any shape relative to the origin — align() is a WebSCAD extension (plain OpenSCAD cannot measure children).",
  params: [
    { key: "x", label: "X axis", type: "select", default: "center", options: ["none", "min", "center", "max"] },
    { key: "y", label: "Y axis", type: "select", default: "center", options: ["none", "min", "center", "max"] },
    { key: "z", label: "Z axis", type: "select", default: "min", options: ["none", "min", "center", "max"] },
  ],
  generate(v) {
    const args = (["x", "y", "z"] as const)
      .filter((k) => v[k] !== "none")
      .map((k) => `${k} = "${v[k]}"`)
      .join(", ");
    return `// align() positions its children's bounding box relative to the origin.
// (WebSCAD extension: "min" | "center" | "max" per axis.)
align(${args})
    translate([13, 7, 5]) sphere(8, $fn = 32);   // <- replace with your shape
`;
  },
  preview(v) {
    return (
      this.generate(v) +
      `\ncolor("red") sphere(1.4, $fn = 24);   // origin marker\n%cube([40, 40, 0.4], center = true);  // ground plane\n`
    );
  },
};

export const PLUGINS: ToolPlugin[] = [
  gearBuilder,
  polarArray,
  gridArray,
  surfaceScatter,
  mirrorCopy,
  alignTool,
];

export function findPlugin(id: string): ToolPlugin | null {
  return PLUGINS.find((p) => p.id === id) ?? null;
}
